"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { SnapshotThumb } from "@/components/SnapshotThumb";
import {
  listMotionEvents,
  listNotifications,
  markAllNotificationsRead,
  markNotificationRead,
  type MotionEvent,
  type Notification,
} from "@/lib/api";

const TYPE_LABELS: Record<Notification["type"], string> = {
  CAMERA_OFFLINE: "Camera offline",
  RECORDING_STOPPED: "Recording stopped",
  STORAGE_QUOTA_WARNING: "Storage quota warning",
  UPLOAD_FAILURE: "Upload failure",
  RETENTION_CLEANUP_FAILURE: "Retention cleanup failure",
  MOTION_DETECTED: "Motion detected",
  PERSON_DETECTED: "Person detected",
  VEHICLE_DETECTED: "Vehicle detected",
};

export default function AlertsPage() {
  const [notifications, setNotifications] = useState<Notification[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [motion, setMotion] = useState<MotionEvent[]>([]);

  async function load() {
    try {
      const res = await listNotifications();
      setNotifications(res.notifications);
      listMotionEvents(20)
        .then((m) => setMotion(m.events))
        .catch(() => undefined);
    } catch {
      setError("Could not load alerts.");
    }
  }

  useEffect(() => {
    load();
  }, []);

  async function onMarkRead(id: string) {
    await markNotificationRead(id);
    await load();
  }

  async function onMarkAllRead() {
    await markAllNotificationsRead();
    await load();
  }

  const unreadCount = notifications?.filter((n) => !n.readAt).length ?? 0;

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h1 className="text-2xl font-semibold">Alerts</h1>
        {unreadCount > 0 && (
          <button onClick={onMarkAllRead} className="text-sm text-emerald-400 hover:underline">
            Mark all as read
          </button>
        )}
      </div>

      {error && <p className="text-sm text-red-400">{error}</p>}

      {notifications && notifications.length === 0 && (
        <div className="rounded-lg border border-dashed border-slate-700 p-8 text-center text-slate-400">
          No alerts yet. Camera offline/recording/storage/retention alerts generated by the
          background worker will show up here.
        </div>
      )}

      {notifications && notifications.length > 0 && (
        <ul className="space-y-2">
          {notifications.map((n) => (
            <li
              key={n.id}
              className={`flex items-start justify-between gap-3 rounded-lg border p-4 text-sm ${
                n.readAt ? "border-slate-800 text-slate-400" : "border-amber-800 bg-amber-950/20"
              }`}
            >
              {n.eventId && <SnapshotThumb eventId={n.eventId} />}
              <div className="min-w-0 flex-1">
                <p className={n.readAt ? "" : "font-medium text-amber-300"}>{TYPE_LABELS[n.type] ?? n.type}</p>
                <p className="mt-1">{n.message}</p>
                <p className="mt-1 text-xs text-slate-500">{new Date(n.createdAt).toLocaleString()}</p>
              </div>
              {!n.readAt && (
                <button onClick={() => onMarkRead(n.id)} className="shrink-0 text-xs text-slate-400 hover:underline">
                  Mark read
                </button>
              )}
            </li>
          ))}
        </ul>
      )}

      <section className="space-y-2">
        <h2 className="text-lg font-medium">Recent motion detections</h2>
        {motion.length === 0 ? (
          <p className="text-sm text-slate-500">
            None yet. Turn on motion detection on a camera&apos;s page (Cameras → camera → Motion detection).
          </p>
        ) : (
          <ul className="space-y-1 text-sm">
            {motion.map((m) => (
              <li key={m.id} className="flex flex-wrap justify-between gap-2 rounded border border-slate-800 px-3 py-2">
                <Link href={`/dashboard/cameras/${m.cameraId}`} className="text-emerald-400 hover:underline">
                  {m.cameraName}
                </Link>
                <span className="text-slate-400">{new Date(m.detectedAt).toLocaleString()}</span>
              </li>
            ))}
          </ul>
        )}
      </section>

      <p className="text-xs text-slate-500">
        Only shows the 50 most recent alerts for this workspace. Repeated identical conditions (e.g.
        a camera staying offline) are deduplicated — see docs/monitoring-and-alerts.md.
      </p>
    </div>
  );
}
